import {
  mkdir,
  readFile,
  readdir,
  rename,
  rmdir,
  unlink,
  writeFile,
} from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { selectOutputs } from './targets.mjs';

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const defaultRulesDirectory = path.join(packageRoot, 'rules');
const sharedSkillsDirectory = path.join(packageRoot, 'skills');
const generatedSkillSignature = '<!-- Generated by @aleradev12/agent-instructions from ';
const generatedInstructionsSignature = '<!-- Generated by @aleradev12/agent-instructions. Edit its config or Markdown sources instead. -->';

const defaultConfiguration = {
  title: 'Project Agent Instructions',
  defaults: {
    enabled: true,
    disabled: [],
  },
  agents: {
    sourceDirectory: 'docs/agents',
    output: 'AGENTS.md',
  },
  skills: {
    enabled: true,
    disabled: [],
    sourceDirectory: 'docs/skills',
    outputs: ['.agents/skills', '.claude/skills'],
  },
};

export async function generateProject(options = {}) {
  const projectRoot = path.resolve(options.projectRoot ?? process.cwd());
  const configPath = resolveInsideProject(
    projectRoot,
    options.configPath ?? 'agent-instructions.config.json',
    'configuration path',
  );
  const configuration = await loadConfiguration(configPath);
  const outputs = selectOutputs(configuration, options.targets);
  const defaultRules = await loadDefaultRules();
  validateDisabledRules(configuration.defaults.disabled, defaultRules);

  const agentDocuments = [];

  if (configuration.defaults.enabled) {
    const disabledRules = new Set(configuration.defaults.disabled);

    for (const rule of defaultRules) {
      if (!disabledRules.has(rule.id)) {
        agentDocuments.push({
          label: `shared:${rule.id}`,
          linkBase: `docs/agents/${rule.fileName}`,
          content: rule.content,
        });
      }
    }
  }

  const localAgentsDirectory = resolveInsideProject(
    projectRoot,
    configuration.agents.sourceDirectory,
    'agents.sourceDirectory',
  );
  const localAgentPaths = await listMarkdownSources(localAgentsDirectory, projectRoot);

  for (const sourcePath of localAgentPaths) {
    const relativePath = toPosix(path.relative(projectRoot, sourcePath));
    agentDocuments.push({
      label: relativePath,
      linkBase: relativePath,
      content: normalizeNewlines(await readFile(sourcePath, 'utf8')),
    });
  }

  if (agentDocuments.length === 0) {
    throw new Error('No agent instructions selected. Enable defaults or add local Markdown sources.');
  }

  const agentOutputs = outputs.agentOutputs.map(({ output, cursorRule }) => {
    const outputPath = resolveInsideProject(projectRoot, output, 'instruction output');
    const relativePath = toPosix(path.relative(projectRoot, outputPath));
    const instructions = renderAgentInstructions(configuration.title, agentDocuments, relativePath);

    return {
      outputPath,
      relativePath,
      content: cursorRule ? `---\nalwaysApply: true\n---\n\n${instructions}` : instructions,
    };
  });

  if (options.targets !== undefined) {
    for (const output of agentOutputs) {
      const existing = await readFileIfPresent(output.outputPath);
      if (existing !== null && !existing.includes(generatedInstructionsSignature)) {
        throw new Error(`Refusing to overwrite manually authored instructions: ${output.relativePath}`);
      }
    }
  }

  let skillCount = 0;

  if (configuration.skills.enabled) {
    const skillsDirectory = resolveInsideProject(
      projectRoot,
      configuration.skills.sourceDirectory,
      'skills.sourceDirectory',
    );
    const sharedSkills = await loadSkillSources(sharedSkillsDirectory, packageRoot);
    validateDisabledSkills(configuration.skills.disabled, sharedSkills);
    const localSkills = await loadSkillSources(skillsDirectory, projectRoot);
    const skillSources = [
      ...sharedSkills.filter(skill => !configuration.skills.disabled.includes(skill.name)),
      ...localSkills,
    ];
    const names = new Set();
    for (const source of skillSources) {
      if (names.has(source.name)) {
        throw new Error(`Duplicate shared and project skill name: ${source.name}`);
      }
      names.add(source.name);
    }
    const outputDirectories = outputs.skillOutputs.map((output, index) => (
      resolveInsideProject(projectRoot, output, `skill output[${index}]`)
    ));

    await synchronizeSkills(skillSources, outputDirectories, projectRoot);
    skillCount = skillSources.length;
  }

  for (const output of agentOutputs) {
    await mkdir(path.dirname(output.outputPath), { recursive: true });
    await writeAtomically(output.outputPath, output.content);
    await verifyFile(output.outputPath, output.content);
  }

  const result = {
    agentDocumentCount: agentDocuments.length,
    skillCount,
    agentOutput: agentOutputs[0].relativePath,
    agentOutputs: agentOutputs.map(output => output.relativePath),
  };

  if (options.log !== false) {
    process.stdout.write(
      `Generated and verified ${result.agentOutputs.join(', ')} from ${result.agentDocumentCount} documents; ${skillCount} project skill${skillCount === 1 ? '' : 's'}.\n`,
    );
  }

  return result;
}

async function loadConfiguration(configPath) {
  const source = await readFileIfPresent(configPath);

  if (source === null) {
    return structuredClone(defaultConfiguration);
  }

  let input;

  try {
    input = JSON.parse(source);
  } catch (error) {
    throw new Error(`Invalid JSON in ${configPath}: ${error.message}`);
  }

  assertObject(input, 'configuration');
  assertKnownKeys(input, ['$schema', 'title', 'defaults', 'agents', 'skills'], 'configuration');

  const configuration = structuredClone(defaultConfiguration);

  if (input.title !== undefined) {
    assertNonEmptyString(input.title, 'title');
    configuration.title = input.title;
  }

  if (input.defaults !== undefined) {
    assertObject(input.defaults, 'defaults');
    assertKnownKeys(input.defaults, ['enabled', 'disabled'], 'defaults');

    if (input.defaults.enabled !== undefined) {
      assertBoolean(input.defaults.enabled, 'defaults.enabled');
      configuration.defaults.enabled = input.defaults.enabled;
    }

    if (input.defaults.disabled !== undefined) {
      assertStringArray(input.defaults.disabled, 'defaults.disabled');
      configuration.defaults.disabled = [...input.defaults.disabled];
    }
  }

  if (input.agents !== undefined) {
    assertObject(input.agents, 'agents');
    assertKnownKeys(input.agents, ['sourceDirectory', 'output'], 'agents');

    for (const key of ['sourceDirectory', 'output']) {
      if (input.agents[key] !== undefined) {
        assertNonEmptyString(input.agents[key], `agents.${key}`);
        configuration.agents[key] = input.agents[key];
      }
    }
  }

  if (input.skills !== undefined) {
    assertObject(input.skills, 'skills');
    assertKnownKeys(input.skills, ['enabled', 'disabled', 'sourceDirectory', 'outputs'], 'skills');

    if (input.skills.enabled !== undefined) {
      assertBoolean(input.skills.enabled, 'skills.enabled');
      configuration.skills.enabled = input.skills.enabled;
    }

    if (input.skills.disabled !== undefined) {
      assertStringArray(input.skills.disabled, 'skills.disabled');
      configuration.skills.disabled = [...input.skills.disabled];
    }

    if (input.skills.sourceDirectory !== undefined) {
      assertNonEmptyString(input.skills.sourceDirectory, 'skills.sourceDirectory');
      configuration.skills.sourceDirectory = input.skills.sourceDirectory;
    }

    if (input.skills.outputs !== undefined) {
      assertStringArray(input.skills.outputs, 'skills.outputs', { allowEmpty: false });
      configuration.skills.outputs = [...input.skills.outputs];
    }
  }

  return configuration;
}

async function loadDefaultRules() {
  const sourcePaths = await listMarkdownSources(defaultRulesDirectory, packageRoot);

  return Promise.all(sourcePaths.map(async sourcePath => ({
    id: path.basename(sourcePath, '.md'),
    fileName: path.basename(sourcePath),
    content: normalizeNewlines(await readFile(sourcePath, 'utf8')),
  })));
}

function validateDisabledRules(disabledRules, defaultRules) {
  const availableRules = new Set(defaultRules.map(rule => rule.id));

  for (const rule of disabledRules) {
    if (!availableRules.has(rule)) {
      throw new Error(`Unknown default rule in defaults.disabled: ${rule}`);
    }
  }
}

function validateDisabledSkills(disabledSkills, sharedSkills) {
  const availableSkills = new Set(sharedSkills.map(skill => skill.name));

  for (const name of disabledSkills) {
    if (!availableSkills.has(name)) {
      throw new Error(`Unknown shared skill in skills.disabled: ${name}`);
    }
  }
}

function renderAgentInstructions(title, documents, outputPath) {
  const sections = documents.map(document => [
    `## ${document.label}`,
    '',
    prepareEmbeddedMarkdown(document.content, document.linkBase, outputPath).trim(),
  ].join('\n'));

  return [
    `# ${title}`,
    '',
    generatedInstructionsSignature,
    '',
    'Shared rules are provided by @aleradev12/agent-instructions; project documents extend them.',
    '',
    ...sections.flatMap((section, index) => index === 0 ? [section] : ['', section]),
    '',
  ].join('\n');
}

function prepareEmbeddedMarkdown(source, relativePath, outputPath) {
  let fence = null;

  return source.split('\n').map(line => {
    const fenceMatch = line.match(/^ {0,3}(`{3,}|~{3,})/);

    if (fence !== null) {
      if (fenceMatch && fenceMatch[1][0] === fence[0] && fenceMatch[1].length >= fence.length
        && line.trim() === fenceMatch[1]) {
        fence = null;
      }
      return line;
    }

    if (fenceMatch) {
      fence = fenceMatch[1];
      return line;
    }

    return rewriteRelativeLinks(line, relativePath, outputPath).replace(/^(#{1,4}) /, '##$1 ');
  }).join('\n');
}

function rewriteRelativeLinks(line, relativePath, outputPath) {
  return line.replace(
    /(\[[^\]]*\]\()([^)]+)(\))/g,
    (match, opening, target, closing) => {
      if (/^(?:[a-z]+:|#|\/)/i.test(target)) {
        return match;
      }

      const [targetPath, fragment] = target.split('#', 2);
      const resolvedPath = path.posix.normalize(
        path.posix.join(path.posix.dirname(relativePath), targetPath),
      );
      const outputRelativePath = path.posix.relative(path.posix.dirname(outputPath), resolvedPath);
      const resolvedTarget = fragment === undefined ? outputRelativePath : `${outputRelativePath}#${fragment}`;

      return `${opening}${resolvedTarget}${closing}`;
    },
  );
}

async function loadSkillSources(directoryPath, projectRoot) {
  const sourcePaths = await listMarkdownSources(directoryPath, projectRoot);
  const sources = [];
  const names = new Set();

  for (const sourcePath of sourcePaths) {
    const relativePath = toPosix(path.relative(projectRoot, sourcePath));
    const source = parseSkillSource(
      normalizeNewlines(await readFile(sourcePath, 'utf8')),
      relativePath,
    );

    if (names.has(source.name)) {
      throw new Error(`Duplicate skill name: ${source.name}`);
    }

    if (path.basename(sourcePath, '.md') !== source.name) {
      throw new Error(`${relativePath} must be named ${source.name}.md`);
    }

    names.add(source.name);
    sources.push(source);
  }

  return sources;
}

function parseSkillSource(content, relativePath) {
  const frontmatter = content.match(/^---\n([\s\S]*?)\n---(?:\n|$)([\s\S]*)$/);

  if (!frontmatter) {
    throw new Error(`${relativePath} must start with YAML frontmatter`);
  }

  const metadata = new Map();

  for (const line of frontmatter[1].split('\n')) {
    const separatorIndex = line.indexOf(':');

    if (separatorIndex < 1) {
      throw new Error(`${relativePath} contains unsupported frontmatter syntax: ${line}`);
    }

    const key = line.slice(0, separatorIndex).trim();
    const rawValue = line.slice(separatorIndex + 1).trim();

    if (!['name', 'description'].includes(key)) {
      throw new Error(`${relativePath} contains unsupported cross-platform field: ${key}`);
    }

    if (metadata.has(key)) {
      throw new Error(`${relativePath} repeats frontmatter field: ${key}`);
    }

    metadata.set(key, parseScalar(rawValue, relativePath, key));
  }

  const name = metadata.get('name');
  const description = metadata.get('description');

  if (!name || !description) {
    throw new Error(`${relativePath} requires non-empty name and description fields`);
  }

  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name) || name.length > 64) {
    throw new Error(`${relativePath} has an invalid skill name: ${name}`);
  }

  if (/anthropic|claude/.test(name)) {
    throw new Error(`${relativePath} uses a provider-reserved word in its skill name`);
  }

  if (description.length > 1024 || /<[^>]*>/.test(description)) {
    throw new Error(`${relativePath} has an invalid skill description`);
  }

  if (frontmatter[2].trim().length === 0) {
    throw new Error(`${relativePath} must contain instructions after the frontmatter`);
  }

  return {
    name,
    relativePath,
    content: content.endsWith('\n') ? content : `${content}\n`,
  };
}

function parseScalar(rawValue, relativePath, key) {
  if (rawValue.startsWith('"')) {
    try {
      const parsed = JSON.parse(rawValue);

      if (typeof parsed === 'string') {
        return parsed;
      }
    } catch {
      // A stable validation error is raised below.
    }

    throw new Error(`${relativePath} has an invalid quoted ${key}`);
  }

  if (rawValue.startsWith("'") && rawValue.endsWith("'")) {
    return rawValue.slice(1, -1).replaceAll("''", "'");
  }

  return rawValue;
}

function renderSkill(source) {
  const frontmatterEnd = source.content.indexOf('\n---', 4) + 4;
  const frontmatter = source.content.slice(0, frontmatterEnd);
  const body = source.content.slice(frontmatterEnd).replace(/^\n+/, '');

  return [
    frontmatter,
    '',
    `${generatedSkillSignature}${source.relativePath}. Edit the source file instead. -->`,
    '',
    body.trimEnd(),
    '',
  ].join('\n');
}

async function synchronizeSkills(sources, outputDirectories, projectRoot) {
  const desiredSkills = new Map(sources.map(source => [source.name, renderSkill(source)]));
  const outputStates = [];

  for (const outputDirectory of outputDirectories) {
    outputStates.push(await inspectSkillOutput(outputDirectory, desiredSkills, projectRoot));
  }

  const conflicts = outputStates.flatMap(state => state.conflicts);

  if (conflicts.length > 0) {
    throw new Error([
      'Refusing to overwrite or remove manually extended skill directories.',
      ...conflicts.map(conflict => `- ${conflict}`),
    ].join('\n'));
  }

  for (const state of outputStates) {
    for (const [name, content] of desiredSkills) {
      const skillDirectory = path.join(state.outputDirectory, name);
      await mkdir(skillDirectory, { recursive: true });
      await writeAtomically(path.join(skillDirectory, 'SKILL.md'), content);
    }

    for (const staleSkill of state.staleSkills) {
      await unlink(staleSkill.skillPath);
      await rmdir(staleSkill.directoryPath);
    }
  }

  for (const outputDirectory of outputDirectories) {
    for (const [name, content] of desiredSkills) {
      await verifyFile(path.join(outputDirectory, name, 'SKILL.md'), content);
    }

    const remainingGenerated = await findGeneratedSkills(outputDirectory);
    const staleNames = remainingGenerated
      .filter(skill => !desiredSkills.has(skill.name))
      .map(skill => skill.name);

    if (staleNames.length > 0) {
      throw new Error(`Stale generated skills remain in ${toPosix(path.relative(projectRoot, outputDirectory))}: ${staleNames.join(', ')}`);
    }
  }
}

async function inspectSkillOutput(outputDirectory, desiredSkills, projectRoot) {
  const conflicts = [];
  const generatedSkills = await findGeneratedSkills(outputDirectory);
  const staleSkills = generatedSkills.filter(skill => !desiredSkills.has(skill.name));

  for (const [name] of desiredSkills) {
    const skillDirectory = path.join(outputDirectory, name);
    const skillPath = path.join(skillDirectory, 'SKILL.md');
    const content = await readFileIfPresent(skillPath);

    if (content !== null && !content.includes(generatedSkillSignature)) {
      conflicts.push(`${toPosix(path.relative(projectRoot, skillPath))} is manually authored`);
    } else if (content === null) {
      const entries = await readDirectoryIfPresent(skillDirectory);

      if (entries.length > 0) {
        conflicts.push(`${toPosix(path.relative(projectRoot, skillDirectory))} is a non-empty manual directory`);
      }
    }
  }

  for (const staleSkill of staleSkills) {
    const entries = await readdir(staleSkill.directoryPath);

    if (entries.length !== 1 || entries[0] !== 'SKILL.md') {
      conflicts.push(`${toPosix(path.relative(projectRoot, staleSkill.directoryPath))} contains extra files`);
    }
  }

  return { outputDirectory, conflicts, staleSkills };
}

async function findGeneratedSkills(outputDirectory) {
  const entries = await readDirectoryIfPresent(outputDirectory);
  const generatedSkills = [];

  for (const entry of entries) {
    if (!entry.isDirectory()) {
      continue;
    }

    const directoryPath = path.join(outputDirectory, entry.name);
    const skillPath = path.join(directoryPath, 'SKILL.md');
    const content = await readFileIfPresent(skillPath);

    if (content?.includes(generatedSkillSignature)) {
      generatedSkills.push({ name: entry.name, directoryPath, skillPath });
    }
  }

  return generatedSkills;
}

async function listMarkdownSources(directoryPath, displayRoot) {
  const entries = await readDirectoryIfPresent(directoryPath);
  const sourcePaths = [];

  for (const entry of entries.sort(compareEntryNames)) {
    if (entry.name.startsWith('.')) {
      continue;
    }

    const entryPath = path.join(directoryPath, entry.name);
    const displayPath = toPosix(path.relative(displayRoot, entryPath));

    if (entry.isDirectory()) {
      throw new Error(`Nested source directories are not supported: ${displayPath}`);
    }

    if (!entry.isFile() || !entry.name.endsWith('.md')) {
      throw new Error(`Source must be a Markdown file: ${displayPath}`);
    }

    sourcePaths.push(entryPath);
  }

  return sourcePaths;
}

function resolveInsideProject(projectRoot, configuredPath, label) {
  assertNonEmptyString(configuredPath, label);

  if (path.isAbsolute(configuredPath)) {
    throw new Error(`${label} must be relative to the project root`);
  }

  const resolvedPath = path.resolve(projectRoot, configuredPath);
  const relativePath = path.relative(projectRoot, resolvedPath);

  if (relativePath === '..' || relativePath.startsWith(`..${path.sep}`)) {
    throw new Error(`${label} must stay inside the project root`);
  }

  return resolvedPath;
}

function assertObject(value, label) {
  if (value === null || typeof value !== 'object' || Array.isArray(value)) {
    throw new Error(`${label} must be an object`);
  }
}

function assertKnownKeys(value, knownKeys, label) {
  const unknownKeys = Object.keys(value).filter(key => !knownKeys.includes(key));

  if (unknownKeys.length > 0) {
    throw new Error(`${label} contains unknown field${unknownKeys.length === 1 ? '' : 's'}: ${unknownKeys.join(', ')}`);
  }
}

function assertNonEmptyString(value, label) {
  if (typeof value !== 'string' || value.trim().length === 0) {
    throw new Error(`${label} must be a non-empty string`);
  }
}

function assertBoolean(value, label) {
  if (typeof value !== 'boolean') {
    throw new Error(`${label} must be a boolean`);
  }
}

function assertStringArray(value, label, options = {}) {
  if (!Array.isArray(value) || value.some(item => typeof item !== 'string' || item.length === 0)) {
    throw new Error(`${label} must be an array of non-empty strings`);
  }

  if (options.allowEmpty === false && value.length === 0) {
    throw new Error(`${label} must not be empty`);
  }

  if (new Set(value).size !== value.length) {
    throw new Error(`${label} must not contain duplicates`);
  }
}

function compareEntryNames(left, right) {
  return left.name === right.name ? 0 : left.name < right.name ? -1 : 1;
}

function normalizeNewlines(value) {
  return value.replaceAll('\r\n', '\n');
}

function toPosix(value) {
  return value.split(path.sep).join('/');
}

async function verifyFile(filePath, expectedContent) {
  const actualContent = await readFileIfPresent(filePath);

  if (actualContent !== expectedContent) {
    throw new Error(`Generated file failed verification: ${filePath}`);
  }
}

async function readFileIfPresent(filePath) {
  try {
    return normalizeNewlines(await readFile(filePath, 'utf8'));
  } catch (error) {
    if (error.code === 'ENOENT') {
      return null;
    }

    throw error;
  }
}

async function readDirectoryIfPresent(directoryPath) {
  try {
    return await readdir(directoryPath, { withFileTypes: true });
  } catch (error) {
    if (error.code === 'ENOENT') {
      return [];
    }

    throw error;
  }
}

async function writeAtomically(filePath, content) {
  const temporaryPath = path.join(
    path.dirname(filePath),
    `.${path.basename(filePath)}.${process.pid}.tmp`,
  );

  try {
    await writeFile(temporaryPath, content, 'utf8');
    await rename(temporaryPath, filePath);
  } catch (error) {
    await unlink(temporaryPath).catch(() => undefined);
    throw error;
  }
}
